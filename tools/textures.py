def gui():
    W, H = 176, 166
    im = Image.new('RGBA', (256, 256), (0, 0, 0, 0)); px = im.load()
    BASE, LIGHT, DARK, EDGE = hx('#c6c6c6'), hx('#ffffff'), hx('#555555'), hx('#000000')
    SLOT_D, SLOT_L, SLOT_B = hx('#373737'), hx('#ffffff'), hx('#8b8b8b')
    for y in range(H):
        for x in range(W):
            e = min(x, y, W - 1 - x, H - 1 - y)
            if e == 0: c = EDGE
            elif e <= 2: c = LIGHT if (x <= 2 or y <= 2) and not (x >= W - 3 or y >= H - 3) else DARK
            else: c = BASE
            px[x, y] = c
    # rounded corners
    for (x, y) in [(0, 0), (1, 0), (0, 1), (W - 1, 0), (W - 2, 0), (W - 1, 1), (0, H - 1), (1, H - 1), (0, H - 2), (W - 1, H - 1), (W - 2, H - 1), (W - 1, H - 2)]:
        px[x, y] = (0, 0, 0, 0)
    for (x, y) in [(1, 1), (W - 2, 1), (1, H - 2), (W - 2, H - 2)]:
        px[x, y] = EDGE
    px[2, 2] = LIGHT; px[W - 3, H - 3] = DARK; px[W - 3, 2] = BASE; px[2, H - 3] = BASE

    def slot(sx, sy, size=18):
        """sx, sy = top-left of the frame. The item is drawn 1 pixel inside (or centred for the big slot)."""
        for y in range(size):
            for x in range(size):
                if x == size - 1 and y == 0 or x == 0 and y == size - 1: c = SLOT_B
                elif x == 0 or y == 0: c = SLOT_D
                elif x == size - 1 or y == size - 1: c = SLOT_L
                else: c = SLOT_B
                px[sx + x, sy + y] = c
    slot(34, 34); slot(70, 34)
    slot(128, 30, 26)
    for row in range(3):
        for col in range(9):
            slot(7 + col * 18, 83 + row * 18)
    for col in range(9):
        slot(7 + col * 18, 141)
    # plus sign between the two inputs
    PLUS = hx('#5a5a5a')
    for i in range(9):
        for t in (0, 1):
            px[57 + i, 42 + t] = PLUS
            px[60 + t + 0, 39 + i] = PLUS
    # arrow to the result
    ARROW = hx('#8b8b8b'); ARROW_D = hx('#5a5a5a')
    for x in range(96, 112):
        for y in range(41, 46):
            px[x, y] = ARROW
    for i in range(8):
        for y in range(36 + i, 51 - i):
            px[112 + i, y] = ARROW
    for x in range(96, 112):
        px[x, 45] = ARROW_D
    for i in range(8):
        px[112 + i, 50 - i] = ARROW_D
    return im

def write_extra():
    base = ASSET_DIR
    os.makedirs(base + '/textures/block', exist_ok=True)
    os.makedirs(base + '/textures/gui', exist_ok=True)
    front = block_side(True)
    front.save(base + '/textures/block/combiner_table_front.png')
    block_side(False).save(base + '/textures/block/combiner_table_side.png')
    block_top().save(base + '/textures/block/combiner_table_top.png')
    block_bottom().save(base + '/textures/block/combiner_table_bottom.png')
    gui().save(base + '/textures/gui/combiner.png')
    # mod icon: the top of the table, enlarged
    block_top().resize((128, 128), Image.NEAREST).save(base + '/icon.png')
    # preview sheet
    prev = Image.new('RGBA', (16 * 12 * 4 + 50 + 176 * 3, 166 * 3 + 20), (70, 72, 80, 255))
    for i, im in enumerate([front, block_side(False), block_top(), block_bottom()]):
        prev.alpha_composite(im.resize((192, 192), Image.NEAREST), (10 + (i % 2) * 202, 10 + (i // 2) * 202))
    prev.alpha_composite(gui().crop((0, 0, 176, 166)).resize((528, 498), Image.NEAREST), (424, 10))
    prev.save(HERE + '/preview_block_gui.png')

if __name__ == '__main__':
    write_extra()
