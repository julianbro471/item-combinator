GLYPH_POS = {'lamp': (5, 4), 'visor': (5, 6), 'wing': (0, 2), 'question': (5, 5)}   # default is bottom-right

def render(template, primary, accent, glyph=None):
    rows = M[template]
    mat = [[None] * 16 for _ in range(16)]
    for y in range(16):
        for x in range(16):
            ch = rows[y][x]
            if ch == '.': continue
            mat[y][x] = primary if ch == 'P' else accent if ch == 'A' else FIXED[ch]
    def at(x, y):
        return mat[y][x] if 0 <= x < 16 and 0 <= y < 16 else None
    img = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    px = img.load()
    for y in range(16):
        for x in range(16):
            m = mat[y][x]
            if m is None: continue
            up, left, down, right = at(x, y - 1), at(x - 1, y), at(x, y + 1), at(x + 1, y)
            if up is None or left is None: shade = 3
            elif down is None or right is None: shade = 1
            elif up != m and left != m: shade = 3
            elif down != m and right != m: shade = 1
            else: shade = 2
            px[x, y] = RAMPS[m][shade]
    # outline on the empty pixels around the shape, in the darkest tone of the material it touches
    for y in range(16):
        for x in range(16):
            if mat[y][x] is not None: continue
            for nx, ny in ((x + 1, y), (x, y + 1), (x - 1, y), (x, y - 1)):
                m = at(nx, ny)
                if m is not None:
                    px[x, y] = RAMPS[m][0]
                    break
    if glyph:
        art, pal = G[glyph]
        h, w = len(art), max(len(r) for r in art)
        gx, gy = GLYPH_POS.get(glyph, (15 - w, 15 - h))
        cells = {(gx + i, gy + j): pal[c] for j, r in enumerate(art) for i, c in enumerate(r) if c != '.'}
        for (x, y) in cells:        # dark rim so the badge reads on top of the item
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1):
                    q = (x + dx, y + dy)
                    if q not in cells and 0 <= q[0] < 16 and 0 <= q[1] < 16 and abs(dx) + abs(dy) == 1:
                        px[q] = (20, 16, 24, 255)
        for (x, y), c in cells.items():
            if 0 <= x < 16 and 0 <= y < 16: px[x, y] = c
    return img

def sheet(images, labels, path, scale=10, cols=10):
    from PIL import ImageDraw
    cw, chh = 16 * scale + 14, 16 * scale + 22
    rows = (len(images) + cols - 1) // cols
    out = Image.new('RGBA', (cols * cw, rows * chh), (70, 72, 80, 255))
    d = ImageDraw.Draw(out)
    for i, (im, lab) in enumerate(zip(images, labels)):
        x, y = (i % cols) * cw + 7, (i // cols) * chh + 4
        d.rectangle([x, y, x + 16 * scale - 1, y + 16 * scale - 1], fill=(139, 139, 139, 255))
        out.alpha_composite(im.resize((16 * scale, 16 * scale), Image.NEAREST), (x, y))
        d.text((x, y + 16 * scale + 3), lab[:26], fill=(255, 255, 255, 255))
    out.save(path)

